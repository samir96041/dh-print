// Generates supabase/seed.sql from src/lib/catalog.ts so DB and fallback never drift.
import { writeFileSync } from "node:fs";
import { CATALOG } from "../src/lib/catalog";
const q = (v: unknown) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
const s = (v: string) => `'${v.replace(/'/g, "''")}'`;
let sql = "-- GENERATED by `npm run seed:gen` from src/lib/catalog.ts. Run after schema.sql.\n";
CATALOG.forEach((p, i) => {
  sql += `insert into divisions(slug,name,blurb,sort) values (${s(p.slug)},${s(p.name)},${s(p.blurb)},${i + 1}) on conflict (slug) do nothing;\n`;
  sql += `insert into products(division_id,slug,name,description,config,pricing,bleed_mm,dpi,supports_csv) select id,${s(p.slug)},${s(p.name)},${s(p.blurb)},${q(p.config)},${q(p.pricing)},${p.bleed_mm},${p.dpi},${p.supports_csv} from divisions where slug=${s(p.slug)} on conflict (slug) do nothing;\n`;
  sql += `insert into templates(product_id,name,layout) select id,'Default',${q(p.template)} from products where slug=${s(p.slug)};\n`;
});
writeFileSync("supabase/seed.sql", sql);
console.log("seed.sql written");
