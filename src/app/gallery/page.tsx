import { CATALOG } from "@/lib/catalog";
import { applyRow, docFromTemplate, docToSvg } from "@/lib/design";

// Sample work per family, rendered from the same templates + engine that produce real print files.
const SAMPLES: Record<string, Record<string, string>[]> = {
  labels: [{ headline: "SMALL BATCH" }, { headline: "HOT SAUCE No.7" }],
  "race-numbers": [{ number: "4821", name: "A. RUNNER" }, { number: "117", name: "J. SMITH" }],
  "mtb-boards": [{ number: "23" }, { number: "9" }],
  stamps: [{ line1: "ACME LTD", line2: "PAID" }],
  trophies: [{ title: "CHAMPION", recipient: "Sam Taylor" }, { title: "MVP 2026", recipient: "Jo Park" }],
  "laser-cut": [{ headline: "WORKSHOP" }],
};

export const metadata = { title: "Gallery — Digital Heroes Print" };

export default function Gallery() {
  return (
    <div className="mx-auto max-w-6xl px-4 pt-10">
      <h1 className="display text-5xl font-bold">Live work</h1>
      <p className="text-muted mt-2 mb-8">Every piece below is generated by the same engine that makes production files.</p>
      {CATALOG.map((p) => (
        <section key={p.slug} className="mb-10">
          <h2 className="display text-2xl font-bold mb-3 flex items-center gap-2"><span className="w-6 h-1.5" style={{ background: p.accent }} />{p.name}</h2>
          <div className="grid sm:grid-cols-2 lg:grid-cols-3 gap-4">
            {SAMPLES[p.slug].map((row, i) => {
              const s = p.config.sizes[0];
              const svg = docToSvg(applyRow(docFromTemplate(p.template, s.w, s.h, 0), row), { bleed: false });
              return <figure key={i} className="panel p-3"><div className="[&>svg]:w-full [&>svg]:h-auto border border-line" dangerouslySetInnerHTML={{ __html: svg }} />
                <figcaption className="mono text-xs text-muted mt-2">{s.label}</figcaption></figure>;
            })}
          </div>
        </section>
      ))}
    </div>
  );
}
